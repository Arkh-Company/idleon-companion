// The names catalog (spec §5.3): the default that ships with the app and the user's copy in names.json.
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readFileSync,
  renameSync,
  writeFileSync,
} from "node:fs";
import { dirname } from "node:path";
import { isObject } from "../../shared/index.ts";
import type {
  Catalog,
  CatalogTable,
  Entry,
  Reading,
} from "../../shared/index.ts";
import defaultNames from "./default-names.json" with { type: "json" };

function isEntries(x: unknown): x is Record<string, Entry> {
  return (
    isObject(x) &&
    Object.values(x).every(
      (e) =>
        isObject(e) &&
        typeof e.name === "string" &&
        (e.status === "deduced" || e.status === "confirmed"),
    )
  );
}

function isCatalog(x: unknown): x is Catalog {
  return (
    isObject(x) &&
    x.version === 1 &&
    isEntries(x.menu) &&
    isEntries(x.menu2) &&
    isEntries(x.codex) &&
    isEntries(x.quickref) &&
    Array.isArray(x.maps) &&
    x.maps.every((m) => typeof m === "string") &&
    isObject(x.afk) &&
    Object.values(x.afk).every((n) => typeof n === "string")
  );
}

function validDefault(x: unknown): Catalog {
  if (!isCatalog(x))
    throw new Error("default-names.json is not a valid catalog");
  return x;
}

/** The catalog generated by scripts/convert-prototype-names.ts. */
export const DEFAULT_CATALOG: Catalog = validDefault(defaultNames);

/** The catalog key of a game number: 0.1 stays "0.1", not "0" (Quik Ref shortcuts). */
export function catalogKey(n: number): string {
  return String(n);
}

/** The user's catalog, or the default when the file is missing or invalid (an invalid file is kept as `.bad`). */
export function loadCatalog(
  userPath: string,
  defaultCatalog: Catalog,
): Catalog {
  if (!existsSync(userPath)) return defaultCatalog;
  let parsed: unknown;
  try {
    parsed = JSON.parse(readFileSync(userPath, "utf8"));
  } catch {
    parsed = undefined;
  }
  if (isCatalog(parsed)) return parsed;
  renameSync(userPath, `${userPath}.bad`);
  return defaultCatalog;
}

/** A copy of the catalog with the player's name for one number, confirmed. */
export function nameEntry(
  cat: Catalog,
  table: CatalogTable,
  key: string,
  name: string,
): Catalog {
  return {
    ...cat,
    [table]: { ...cat[table], [key]: { name, status: "confirmed" } },
  };
}

/** Writes the user's catalog, copying the previous file to `.bak` first. */
export function saveCatalog(userPath: string, cat: Catalog): void {
  mkdirSync(dirname(userPath), { recursive: true });
  if (existsSync(userPath)) copyFileSync(userPath, `${userPath}.bak`);
  writeFileSync(userPath, JSON.stringify(cat));
}

/** The numbers of this reading the catalog has no name for. The Codex tab counts only while the Codex is open. */
export function unnamedIn(
  cat: Catalog,
  r: Reading,
): { table: CatalogTable; key: string }[] {
  const out: { table: CatalogTable; key: string }[] = [];
  const check = (table: CatalogTable, n: number) => {
    const key = catalogKey(n);
    if (!Object.hasOwn(cat[table], key)) out.push({ table, key });
  };
  check("menu", r.menu);
  check("menu2", r.menu2);
  if (r.menu === 3 && r.codexTab !== null) check("codex", r.codexTab);
  return out;
}
